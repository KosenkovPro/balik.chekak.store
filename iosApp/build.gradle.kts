import org.jetbrains.kotlin.gradle.dsl.KotlinMultiplatformExtension
import org.jetbrains.kotlin.gradle.plugin.mpp.Framework
import org.jetbrains.kotlin.gradle.plugin.mpp.KotlinNativeTarget
import java.io.File

/**
 * iOS-обёртка над общим Kotlin-кодом.
 *
 * Весь общий код (UI, Room KMP, парсеры) живёт в модуле `:composeApp`, который
 * собирает статический фреймворк `ComposeApp`. Этот модуль отвечает только за
 * настройку Xcode-проекта `iosApp.xcodeproj`:
 *
 *  * объявляет iOS-цели Kotlin/Native — из них берётся информация о toolchain;
 *  * задача `xcodeConfig` генерирует `Configuration/Config.xcconfig`, который
 *    подключён в Xcode как base configuration для всех таргетов.
 *
 * Модуль **не** собирает собственный фреймворк: дублировать `ComposeApp.framework`
 * нельзя, файл сборки Xcode всегда вызывает `:composeApp:embedAndSignAppleFrameworkForXcode`.
 */
plugins {
    kotlin("multiplatform") version "2.2.10"
    id("org.jetbrains.kotlin.plugin.compose") version "2.2.10"
}

kotlin {
    // iOS-цели нужны, чтобы задача `xcodeConfig` знала про Kotlin/Native toolchain.
    // Сам фреймворк `ComposeApp` собирает модуль `:composeApp`.
    iosX64()
    iosArm64()
    iosSimulatorArm64()
}

/**
 * Путь к папке, куда Gradle складывает `ComposeApp.framework` для Xcode.
 * Вычисляется из реального buildDir модуля `:composeApp`, а не жёстко задан.
 */
val composeAppBuildDir: String = runCatching {
    val composeApp = rootProject.findProject(":composeApp")
    composeApp?.layout?.buildDirectory?.get()?.asFile?.absolutePath
        ?: File(rootProject.projectDir, "composeApp/build").absolutePath
}.getOrElse {
    File(rootProject.projectDir, "composeApp/build").absolutePath
}

/**
 * Имя фреймворка берётся из Gradle-модели модуля `:composeApp`
 * (`binaries.framework { baseName = "ComposeApp" }`).
 */
val frameworkName: String = runCatching {
    val composeApp = rootProject.findProject(":composeApp")
    val extension = composeApp?.extensions?.findByType(KotlinMultiplatformExtension::class.java)
    extension?.targets
        ?.withType(KotlinNativeTarget::class.java)
        ?.mapNotNull { target ->
            target.binaries.withType(Framework::class.java).firstOrNull()?.baseName
        }
        ?.firstOrNull()
}.getOrNull() ?: "ComposeApp"

/** Относительный путь от каталога `iosApp` до buildDir модуля `:composeApp`. */
val relativeComposeAppBuildDir: String = runCatching {
    val from = File(project.projectDir.absolutePath).toPath().toAbsolutePath().normalize()
    val to = File(composeAppBuildDir).toPath().toAbsolutePath().normalize()
    from.relativize(to).toString().replace(File.separatorChar, '/')
}.getOrElse { "../composeApp/build" }

/**
 * Генерирует `Configuration/Config.xcconfig` — файл, который Xcode-проект использует
 * как base configuration. В нём собраны идентификаторы приложения, путь к фреймворку
 * `ComposeApp` (по которому Xcode его линкует), параметры SDK/конфигурации и пути
 * к Kotlin/Native toolchain.
 */
tasks.register("xcodeConfig") {
    group = "kotlin"
    description = "Generates iosApp/Configuration/Config.xcconfig for the Xcode project"

    val projectDirPath = project.projectDir.absolutePath

    doLast {
        // Пути к Kotlin/Native вычисляются внутри doLast: при конфигурации модуля
        // на машине без Xcode/macOS не должен скачиваться native-тулчейн.
        val konanHome = project.resolveKonanHome()
        val kotlincPath = if (konanHome.isEmpty()) "" else "$konanHome/bin/konanc"
        val kotlinGradlePluginLocation = project.resolveKotlinGradlePluginLocation()

        val lines = listOf(
            "// This file is generated by the Gradle task \":iosApp:xcodeConfig\".",
            "// Do not edit it manually — regenerate with: ./gradlew :iosApp:xcodeConfig",
            "//",
            "// The Xcode project (iosApp.xcodeproj) uses it as the base configuration",
            "// (baseConfigurationReference) for every target and every build configuration.",
            "",
            "// --- Application identifiers ---",
            "TEAM_ID=",
            "BUNDLE_ID=store.chekak.balik",
            "SHARE_EXTENSION_BUNDLE_ID=store.chekak.balik.ShareExtension",
            "WIDGET_BUNDLE_ID=store.chekak.balik.Widget",
            "APP_NAME=ЧёКак: Балик",
            "APP_GROUP=group.store.chekak.balik",
            "IPHONEOS_DEPLOYMENT_TARGET=15.0",
            "",
            "// --- Kotlin / Compose Multiplatform framework ---",
            "// The framework itself is produced by the shared module \":composeApp\"",
            "// (binaries.framework { baseName = \"ComposeApp\"; isStatic = true }).",
            "KOTLIN_FRAMEWORK_NAME=$frameworkName",
            "KOTLIN_FRAMEWORK_SEARCH_PATHS=\$(SRCROOT)/$relativeComposeAppBuildDir/xcode-frameworks/\$(CONFIGURATION)/\$(SDK_NAME)",
            "FRAMEWORK_SEARCH_PATHS=\$(inherited) \$(KOTLIN_FRAMEWORK_SEARCH_PATHS)",
            "KOTLIN_CONFIGURATION=\$(CONFIGURATION)",
            "KOTLIN_SDK_NAME=\$(SDK_NAME)",
            "KOTLIN_TARGET_NAME=\$(TARGET_NAME)",
            "KOTLIN_ARCHS=\$(ARCHS)",
            "",
            "// --- Kotlin/Native toolchain ---",
            "// Absolute paths are resolved on the build machine by \":iosApp:xcodeConfig\".",
            "KOTLIN_NATIVE_HOME=$konanHome",
            "KOTLIN_NATIVE_KOTLINC=$kotlincPath",
            "KOTLIN_GRADLE_PLUGIN_LOCATION=$kotlinGradlePluginLocation",
            ""
        )

        val target = File(projectDirPath, "Configuration/Config.xcconfig")
        target.parentFile?.mkdirs()
        val content = lines.joinToString("\n")
        if (target.exists() && target.readText() == content) {
            logger.lifecycle("${target.absolutePath} is up to date")
        } else {
            target.writeText(content)
            logger.lifecycle("Generated ${target.absolutePath}")
        }
    }
}

/**
 * Каталог Kotlin/Native (`~/.konan/kotlin-native-prebuilt-...`).
 * Берётся из переменной окружения `KONAN_HOME` или из расширения Kotlin/Native.
 */
fun Project.resolveKonanHome(): String {
    System.getenv("KONAN_HOME")?.takeIf { it.isNotBlank() }?.let { return it }
    val extension = extensions.findByName("kotlinNative") ?: return ""
    return runCatching {
        val getter = extension.javaClass.methods.firstOrNull { it.name == "getKonanHome" }
            ?: extension.javaClass.methods.firstOrNull { it.name == "getKonanDataDir" }
        getter?.invoke(extension)?.toString().orEmpty()
    }.getOrDefault("")
}

/**
 * Расположение jar-файла плагина Kotlin Gradle Plugin — тот же plugin-артефакт,
 * который резолвится из `pluginManagement` в settings.gradle.kts.
 */
fun Project.resolveKotlinGradlePluginLocation(): String {
    val plugin = plugins.findPlugin("org.jetbrains.kotlin.multiplatform") ?: return ""
    return runCatching {
        plugin.javaClass.protectionDomain?.codeSource?.location?.toString().orEmpty()
    }.getOrDefault("")
}
