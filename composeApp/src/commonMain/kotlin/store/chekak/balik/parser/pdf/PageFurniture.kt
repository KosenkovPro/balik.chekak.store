package store.chekak.balik.parser.pdf

/**
 * Служебные строки выписки: колонтитулы, шапка таблицы, итоги, подпись.
 *
 * Их знают и разбор выписки, и устранение омоглифов. Подвал страницы стоит
 * сразу за последней операцией, и без его отсечения слова подвала тянутся
 * в описание последней операции: а это, например, кириллические слова,
 * которые сбивают выбор алфавита у названия магазина.
 */
object PageFurniture {

    private val patterns = listOf(
        // Подвал страницы: «АО «ТБанк» универсальная лицензия…».
        // При распознавании по картинке название банка читается как
        // «АО «TBaHK»» или «АО «ТБаню», поэтому сверяем только первые
        // буквы и допускаем латиницу — иначе подвал попадает в описание
        // последней операции страницы.
        Regex("""^АО\s+«\s*[ТT][БB][АA][НH][КK]""", RegexOption.IGNORE_CASE),
        Regex("""^БИК\s+\d"""),
        // Второй строкой подвала идёт «…00974 ИНН 7710140679 КПП 77…»:
        // хвост номера счёта отрывается на следующую строку.
        Regex("""^\d{0,6}\s*ИНН\s+\d"""),
        Regex("""^Дата и время\s+Дата\b"""),
        Regex("""^операции списания\b"""),
        Regex("""^(Пополнения|Расходы)\s*:""", RegexOption.IGNORE_CASE),
        Regex("""^С уважением,"""),
        Regex("""^Руководитель\s+Управления"""),
        Regex("""^\d{1,3}$"""),
    )

    /** Служебная ли строка: в операцию она не входит. */
    fun isFurniture(line: String): Boolean = patterns.any { it.containsMatchIn(line) }
}
