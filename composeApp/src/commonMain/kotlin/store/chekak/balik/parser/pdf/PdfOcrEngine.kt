package store.chekak.balik.parser.pdf

/**
 * Распознавание текста на изображении страницы PDF.
 *
 * Нужно для сканов: в них нет текстового слоя, и обычное извлечение текста
 * возвращает пустоту. Реализации платформенные:
 *  * Android — Tesseract (TessTwo) поверх картинки, отрендеренной PDFBox;
 *  * iOS — системный Vision поверх снимка страницы из PDFKit;
 *  * JVM (desktop) — распознавания нет, приложение работает только в тестах.
 */
expect object PdfOcrEngine {

    /**
     * Распознаёт страницы PDF как изображение.
     *
     * @return страницы со словами и их рамками; пустой список, если OCR
     *   недоступен или не удалось распознать ни одной страницы.
     */
    suspend fun recognizePages(bytes: ByteArray): List<OcrPage>
}
