package store.chekak.balik.parser.pdf

/**
 * Слово, распознанное на странице: текст и его рамка в пикселях страницы.
 *
 * Координаты нужны, чтобы собрать слова обратно в строки таблицы: у выписки
 * ячейки одной строки находятся рядом по вертикали, а по горизонтали их
 * разделяют большие промежутки.
 */
data class OcrWord(
    val text: String,
    val left: Int,
    val top: Int,
    val right: Int,
    val bottom: Int,
    /** Уверенность распознавания, % (0 — если движок её не сообщает). */
    val confidence: Float = 0f,
    /**
     * То же слово, прочитанное моделью с латиницей.
     *
     * Заполняется движком для слов, которые можно прочитать и так и так:
     * кириллические буквы АВЕКМНОРСТУХ неотличимы от латинских, и движок
     * выбирает алфавит по странице целиком. Переписывать буквы по таблице
     * нельзя — «МОСКВА» настоящее кириллическое слово, — поэтому второе
     * чтение берём у движка.
     */
    val latinText: String? = null,
    /** Уверенность латинского чтения, %. */
    val latinConfidence: Float = 0f,
    /**
     * То же слово, прочитанное моделью с кириллицей.
     *
     * Нужна для обратного случая: движок читает кириллическое слово латиницей
     * («Отмена» → «ОТMeHa», «ТОО» → «TOO»). Модель с латиницей тут помочь
     * не может — поэтому и это прочтение берём у движка.
     */
    val cyrillicText: String? = null,
    /** Уверенность кириллического чтения, %. */
    val cyrillicConfidence: Float = 0f,
)

/** Страница с распознанными словами. */
data class OcrPage(
    val width: Int,
    val height: Int,
    val words: List<OcrWord>,
)
